/**
 * Builds a standard LRC document. Lines are distributed between `start` and `end`
 * seconds; an empty string marks an instrumental break (rendered as ♪).
 */
function buildLrc(meta: { ti: string; ar: string; al: string }, start: number, end: number, lines: string[]): string {
  const step = (end - start) / lines.length;
  const stamp = (t: number) => {
    const m = Math.floor(t / 60);
    const s = t - m * 60;
    return `[${String(m).padStart(2, "0")}:${s.toFixed(2).padStart(5, "0")}]`;
  };
  const head = `[ti:${meta.ti}]\n[ar:${meta.ar}]\n[al:${meta.al}]\n[by:MateMusic]\n${stamp(0)}♪ ${meta.ti} — ${meta.ar}\n`;
  return head + lines.map((l, i) => `${stamp(start + i * step)}${l || "♪"}`).join("\n");
}

